export type T = (key: TKey, vars?: Record<string, string | number>) => string;

/** t('rowsCount', { n: 5 }) → "5 та қатор" */
export const makeT =
  (lang: Lang): T =>
  (key, vars) =>
    DICTS[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars?.[k] ?? ''));

export const I18n = createContext<T>(makeT('uz'));
export const useT = () => useContext(I18n);

/** Birlik nomi tanlangan tilda: "pcs" → "та" / "шт" / "pcs" */
export const unitLabel = (t: T, u: string) => (u === 'pcs' ? t('unitPcs') : u === 'm' ? t('unitM') : u);
